#!/usr/bin/env node
/* Build supabase/staging-bootstrap.sql — one paste that stands a new Supabase
   project up as staging.

   Staging has to be built from the SAME statements as production, or it stops
   being evidence: a gate that passes against a hand-typed schema says nothing
   about the real one. So this concatenates the four source files in the order
   they must run, rather than anyone maintaining a fifth copy by hand.

   The one thing it drops is schema-update.sql's seed, which writes REPLACE_ME
   as every qikink_product_id — product-map-seed.sql carries the real Qikink
   ids, and inserting rows only to overwrite them makes the log harder to read.

     node scripts/build-staging-bootstrap.mjs
*/
import { readFile, writeFile } from "node:fs/promises";

const SOURCES = [
  ["1 · base schema (schema.sql)", "supabase/schema.sql"],
  ["2 · launch update — DDL only (schema-update.sql)", "supabase/schema-update.sql"],
  ["3 · product map seed (product-map-seed.sql)", "supabase/product-map-seed.sql"],
  ["4 · order-lifecycle redesign (schema-redesign.sql)", "supabase/schema-redesign.sql"],
];
const OUT = "supabase/staging-bootstrap.sql";
const SEED_MARKER = "-- Seed with the Drucka catalogue";

const rule = "-- ─────────────────────────────────────────────────────────────────";
const section = (title, body) => ["", rule, `-- ${title}`, rule, body.trim(), ""].join("\n");

const header = [
  "-- ════════════════════════════════════════════════════════════════════",
  "-- DRUCKA staging bootstrap — paste into a NEW Supabase project, run once.",
  "--",
  "-- GENERATED by scripts/build-staging-bootstrap.mjs from, in order:",
  "--   supabase/schema.sql · schema-update.sql (DDL only) ·",
  "--   product-map-seed.sql · schema-redesign.sql",
  "-- Do not hand-edit: change the source file and regenerate, so staging and",
  "-- production are built from the same statements.",
  "--",
  "-- schema-update.sql ships a seed that writes REPLACE_ME as every",
  "-- qikink_product_id; it is left out here, because product-map-seed.sql",
  "-- carries the real Qikink ids the app actually sends.",
  "--",
  "-- Every statement is idempotent — safe to re-run.",
  "-- ════════════════════════════════════════════════════════════════════",
  "",
].join("\n");

const verify = section(
  "VERIFY — expect 2, 1, 1, 5, 14 mappings, 0 placeholders",
  `select
  (select count(*) from information_schema.columns
     where table_name='orders' and column_name in ('fulfill_attempts','next_retry_at')) as columns_expect_2,
  (select count(*) from pg_indexes
     where tablename='orders' and indexname='orders_fulfillment_queue_idx') as index_expect_1,
  (select count(*) from pg_constraint where conname='orders_qikink_status_chk') as constraint_expect_1,
  (select count(*) from information_schema.columns where table_name='order_events') as event_cols_expect_5,
  (select count(*) from public.product_map) as mappings_expect_14,
  (select count(*) from public.product_map where qikink_product_id = 'REPLACE_ME') as placeholders_expect_0;`
);

let out = header;
for (const [title, path] of SOURCES) {
  let body = await readFile(path, "utf8");
  if (path.endsWith("schema-update.sql")) {
    const cut = body.indexOf(SEED_MARKER);
    /* fail loudly rather than silently shipping REPLACE_ME rows to staging */
    if (cut < 0) throw new Error(`${path}: could not find the seed block marked "${SEED_MARKER}"`);
    body = body.slice(0, cut);
  }
  out += section(title, body);
}
out += verify;

await writeFile(OUT, out);
console.log(`wrote ${OUT} — ${out.split("\n").length} lines from ${SOURCES.length} sources`);
